# -*- coding: utf-8 -*-
"""سوئیچ سراسری «بخش نمایندگی‌ها» برای بات اصلی.

یک کلید در «پنل مدیریت ← نمایندگی‌ها» این تنظیم را عوض می‌کند:

* ``reseller_section_enabled = "1"`` (پیش‌فرض): همه‌چیز مثل قبل است.
* ``"0"``: تمام مسیرهای نمایندگی برای کاربران — منوی سطوح، درخواست نمایندگی،
  پنل نماینده و ساخت کانفیگ از آن پنل — مخفی و بسته می‌شود. مدیریت
  نماینده‌های فعلی در پنل مدیریت همچنان در دسترس می‌ماند و با همان کلید
  می‌توان بخش را دوباره روشن کرد.

این ماژول عمداً هیچ وابستگی‌ای به aiogram ندارد تا منطق آن در تست‌های CI
(که تله‌گرام نصب نیست) قابل بررسی باشد.
"""

from i18n import tr

SETTING_KEY = "reseller_section_enabled"
TOGGLE_CALLBACK = "adm_reseller_section_toggle"


def is_enabled(db) -> bool:
    """آیا بخش نمایندگی برای کاربران باز است؟ خطا یعنی «باز» تا ربات قفل نشود."""
    try:
        return str(db.get_setting(SETTING_KEY, "1")).strip() != "0"
    except Exception:
        return True


def toggle_label(db) -> str:
    """برچسب دکمهٔ سوئیچ بر اساس وضعیت فعلی."""
    if is_enabled(db):
        return "🔴 خاموش کردن بخش نمایندگی‌ها"
    return "🟢 روشن کردن بخش نمایندگی‌ها"


def status_text(db) -> str:
    """وضعیت و توضیح کوتاه برای سرصفحهٔ زیرمنوی «نمایندگی‌ها»."""
    if is_enabled(db):
        return (
            tr("وضعیت بخش نمایندگی: 🟢 روشن") + "\n" +
            tr("با این کلید بخش نمایندگی (درخواست نمایندگی و پنل نماینده) را "
               "برای کاربران خاموش یا روشن کنید؛ مدیریت نماینده‌های فعلی همیشه "
               "در دسترس است.")
        )
    return (
        tr("وضعیت بخش نمایندگی: 🔴 خاموش") + "\n" +
        tr("بخش نمایندگی برای کاربران مخفی است. با کلید زیر دوباره روشنش کنید.")
    )


def toggle_message(turning_off: bool) -> str:
    """پیام کوتاه بعد از زدن دکمه (برای answer تلگرام)."""
    if turning_off:
        return tr("بخش نمایندگی خاموش شد؛ دکمه‌های آن از منوی کاربران حذف می‌شود.")
    return tr("بخش نمایندگی روشن شد؛ دکمه‌های آن به منوی کاربران برگشت.")


def blocked_text() -> str:
    """پاسخ یکسان به کاربر وقتی بخش خاموش است."""
    return tr("بخش نمایندگی در حال حاضر خاموش است.")
